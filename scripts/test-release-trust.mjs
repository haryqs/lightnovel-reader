import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve, sep } from 'node:path'
import { checkReleaseTrust } from './check-release-trust.mjs'

const workDir = mkdtempSync(join(tmpdir(), 'lnr-release-trust-test-'))
const markerPath = join(workDir, '.lnr-release-trust-test')
const pluginTrustPath = join(workDir, 'plugin_trust.rs')
const tauriConfigPath = join(workDir, 'tauri.conf.json')

function assertCheck(condition, message, details) {
  if (!condition) {
    throw new Error(details ? `${message}: ${JSON.stringify(details)}` : message)
  }
}

function writeFixture({
  keys,
  requireSignatures,
  updaterPubkey,
  createUpdaterArtifacts = true,
  updaterInstallMode = 'quiet',
}) {
  const keySource = keys.map((key) => `
    TrustedPluginKey {
        key_id: "${key.keyId}",
        public_key_base64: "${key.publicKeyBase64}",
    },`).join('')
  writeFileSync(
    pluginTrustPath,
    `use reading_core::plugin_repository::TrustedPluginKey;
pub const OFFICIAL_PLUGIN_KEYS: &[TrustedPluginKey<'static>] = &[${keySource}
];
pub const REQUIRE_OFFICIAL_PLUGIN_SIGNATURES: bool = ${requireSignatures};
`,
    'utf8',
  )
  writeFileSync(
    tauriConfigPath,
    `${JSON.stringify({
      bundle: { createUpdaterArtifacts },
      plugins: { updater: { pubkey: updaterPubkey, windows: { installMode: updaterInstallMode } } },
    }, null, 2)}\n`,
    'utf8',
  )
}

function cleanup() {
  const resolvedTmp = resolve(tmpdir())
  const resolvedWork = resolve(workDir)
  if (!resolvedWork.startsWith(`${resolvedTmp}${sep}`)) {
    throw new Error(`refusing to remove path outside the system temp directory: ${resolvedWork}`)
  }
  rmSync(resolvedWork, { recursive: true, force: true })
}

try {
  writeFileSync(markerPath, 'generated by test-release-trust.mjs\n', 'utf8')
  const validKey = {
    keyId: 'lnr-plugin-2026-01',
    publicKeyBase64: Buffer.alloc(32, 7).toString('base64'),
  }

  writeFixture({ keys: [validKey], requireSignatures: true, updaterPubkey: 'RWQ-release-public-key' })
  const ready = checkReleaseTrust({ pluginTrustPath, tauriConfigPath })
  assertCheck(ready.ok, 'valid release trust fixture should pass', ready)

  writeFixture({
    keys: [],
    requireSignatures: false,
    updaterPubkey: '',
    createUpdaterArtifacts: false,
    updaterInstallMode: 'passive',
  })
  const unprovisioned = checkReleaseTrust({ pluginTrustPath, tauriConfigPath })
  assertCheck(!unprovisioned.ok, 'unprovisioned release trust fixture should fail', unprovisioned)
  assertCheck(unprovisioned.errors.length === 5, 'unprovisioned fixture should report all release prerequisites', unprovisioned)
  assertCheck(
    unprovisioned.errors.some((error) => error.includes('createUpdaterArtifacts')),
    'disabled updater artifacts should be reported',
    unprovisioned,
  )
  assertCheck(
    unprovisioned.errors.some((error) => error.includes('installMode')),
    'interactive updater install mode should be reported',
    unprovisioned,
  )

  writeFileSync(
    pluginTrustPath,
    `${readFileSync(pluginTrustPath, 'utf8')}\n// TrustedPluginKey { key_id: "decoy", public_key_base64: "${validKey.publicKeyBase64}" }\n`,
    'utf8',
  )
  const commentedDecoy = checkReleaseTrust({ pluginTrustPath, tauriConfigPath })
  assertCheck(
    commentedDecoy.pluginKeyIds.length === 0,
    'keys outside OFFICIAL_PLUGIN_KEYS must not satisfy the release guard',
    commentedDecoy,
  )

  writeFixture({
    keys: [validKey, validKey, { keyId: 'bad-key', publicKeyBase64: 'not-base64' }],
    requireSignatures: true,
    updaterPubkey: 'RWQ-release-public-key',
  })
  const invalidKeys = checkReleaseTrust({ pluginTrustPath, tauriConfigPath })
  assertCheck(!invalidKeys.ok, 'duplicate and malformed plugin keys should fail', invalidKeys)
  assertCheck(invalidKeys.errors.some((error) => error.includes('duplicated')), 'duplicate keyId should be reported', invalidKeys)
  assertCheck(invalidKeys.errors.some((error) => error.includes('32 bytes')), 'malformed public key should be reported', invalidKeys)

  console.log('test-release-trust: OK')
} finally {
  cleanup()
}
