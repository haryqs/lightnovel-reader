import {
  createHash,
  generateKeyPairSync,
  verify,
} from 'node:crypto'
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve, sep } from 'node:path'
import process from 'node:process'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const keepData = process.argv.includes('--keep-data')
const workDir = mkdtempSync(join(tmpdir(), 'lnr-plugin-signature-smoke-'))
const markerPath = join(workDir, '.lnr-plugin-signature-smoke')
const repositoryPath = join(workDir, 'repository.json')
const signedRepositoryPath = join(workDir, 'repository.signed.json')
const packagePath = join(workDir, 'aozora-smoke-source.zip')
const privateKeyPath = join(workDir, 'ephemeral-private-key.pem')
const keyId = 'smoke-ed25519-2026'

function fail(message, details) {
  throw new Error(details ? `${message}\n${details}` : message)
}

function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: repoRoot,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
    windowsHide: true,
  })
  if (result.status !== 0) {
    fail(
      `${command} ${args.join(' ')} failed with exit code ${result.status}`,
      `${result.stdout || ''}${result.stderr || ''}`.trim(),
    )
  }
  return `${result.stdout || ''}${result.stderr || ''}`
}

function assertCheck(condition, message, details) {
  if (!condition) fail(message, details === undefined ? '' : JSON.stringify(details, null, 2))
}

function cleanup() {
  if (keepData) return
  const resolvedTmp = resolve(tmpdir())
  const resolvedWork = resolve(workDir)
  if (!resolvedWork.startsWith(`${resolvedTmp}${sep}`) || !existsSync(markerPath)) {
    fail('refusing to clean an unverified smoke directory', resolvedWork)
  }
  rmSync(resolvedWork, { recursive: true, force: true })
}

try {
  writeFileSync(markerPath, 'generated by smoke-plugin-repository-signature.mjs\n', 'utf8')

  run(process.execPath, [
    join(repoRoot, 'scripts', 'new-smoke-plugin-repository.mjs'),
    '--out-dir',
    workDir,
    '--base-url',
    'https://plugins.example.invalid/smoke',
    '--plugin-id',
    'aozora-smoke-source',
  ])

  const { privateKey, publicKey } = generateKeyPairSync('ed25519')
  const publicKeyDer = publicKey.export({ type: 'spki', format: 'der' })
  const publicKeyBase64 = publicKeyDer.subarray(publicKeyDer.length - 32).toString('base64')
  writeFileSync(
    privateKeyPath,
    privateKey.export({ type: 'pkcs8', format: 'pem' }),
    { mode: 0o600 },
  )

  const signerOutput = run(process.execPath, [
    join(repoRoot, 'scripts', 'sign-plugin-repository.mjs'),
    '--repository',
    repositoryPath,
    '--package-dir',
    workDir,
    '--private-key',
    privateKeyPath,
    '--key-id',
    keyId,
    '--expected-public-key-base64',
    publicKeyBase64,
    '--out',
    signedRepositoryPath,
  ])

  const repository = JSON.parse(readFileSync(signedRepositoryPath, 'utf8'))
  assertCheck(repository.entries?.length === 1, 'signed repository should contain one entry', repository)
  const entry = repository.entries[0]
  const packageBytes = readFileSync(packagePath)
  const signatureBytes = Buffer.from(entry.signature?.value || '', 'base64')
  const packageSha256 = createHash('sha256').update(packageBytes).digest('hex')

  assertCheck(entry.signature?.algorithm === 'ed25519', 'signature algorithm should be ed25519', entry.signature)
  assertCheck(entry.signature?.keyId === keyId, 'signature keyId should match the smoke key', entry.signature)
  assertCheck(signatureBytes.length === 64, 'Ed25519 signature should decode to 64 bytes', entry.signature)
  assertCheck(entry.packageSha256 === packageSha256, 'signed package SHA-256 should match the zip')
  assertCheck(entry.packageSize === packageBytes.length, 'signed package size should match the zip')
  assertCheck(
    verify(null, packageBytes, publicKey, signatureBytes),
    'signature should verify over the exact zip bytes',
  )
  run(process.execPath, [
    join(repoRoot, 'scripts', 'verify-plugin-repository-release.mjs'),
    '--repository',
    signedRepositoryPath,
    '--package-dir',
    workDir,
    '--public-key-base64',
    publicKeyBase64,
    '--key-id',
    keyId,
  ])

  const tamperedBytes = Buffer.from(packageBytes)
  tamperedBytes[Math.floor(tamperedBytes.length / 2)] ^= 0x01
  assertCheck(
    !verify(null, tamperedBytes, publicKey, signatureBytes),
    'signature must reject a one-byte package mutation',
  )

  const { publicKey: unrelatedPublicKey } = generateKeyPairSync('ed25519')
  assertCheck(
    !verify(null, packageBytes, unrelatedPublicKey, signatureBytes),
    'signature must reject an unrelated key',
  )

  run('cargo', ['test', '-p', 'reading-core', 'plugin_repository::tests', '--', '--nocapture'])
  run('cargo', ['test', '-p', 'reader', 'plugin_repository_command_tests', '--', '--nocapture'])

  const publicKeyLine = signerOutput
    .split(/\r?\n/)
    .find((line) => line.startsWith('sign-plugin-repository: publicKeyBase64='))
  assertCheck(publicKeyLine, 'signer should print the public key for keyring enrollment', signerOutput)

  console.log(
    JSON.stringify(
      {
        ok: true,
        keyId,
        packageBytes: packageBytes.length,
        packageSha256,
        checks: [
          'signer output verifies over raw zip bytes',
          'signing key matches the expected compiled public key',
          'independent public-key-only release verification passes',
          'one-byte package mutation is rejected',
          'unrelated public key is rejected',
          'reading-core repository signature tests pass',
          'Tauri downloaded-package verification tests pass',
        ],
        keptDataAt: keepData ? workDir : null,
      },
      null,
      2,
    ),
  )
  console.log('smoke-plugin-repository-signature: OK')
} catch (error) {
  console.error('smoke-plugin-repository-signature: FAILED')
  console.error(error?.stack || error?.message || String(error))
  process.exitCode = 1
} finally {
  try {
    cleanup()
  } catch (cleanupError) {
    console.error(cleanupError?.stack || cleanupError?.message || String(cleanupError))
    process.exitCode = 1
  }
}
